import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import zlib from 'node:zlib'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '../..')
const wasmBuildDir = path.resolve(rootDir, 'cmake-build-wasm')

const REQUIRED_OPENCC_FILES = [
  't2s.json',
  'TSPhrases.ocd2',
  'TSCharacters.ocd2',
  'TSCharactersExt.ocd2',
  'CJK_Compatibility_Ideographs.ocd2',
]

function setupEnv() {
  const env = { ...process.env }
  const isWin = process.platform === 'win32'
  const checkCmd = isWin ? 'where' : 'which'

  // If emcmake is already in PATH, nothing to configure
  const inPath = spawnSync(checkCmd, ['emcmake'], { env, stdio: 'ignore' }).status === 0
  if (inPath) {
    return env
  }

  // Otherwise, check EMSDK environment variable or standard locations
  const emsdkCandidates = [
    process.env.EMSDK,
    path.join(os.homedir(), 'emsdk'),
  ].filter(Boolean)

  for (const emsdkPath of emsdkCandidates) {
    if (fs.existsSync(emsdkPath)) {
      const upstream = path.join(emsdkPath, 'upstream', 'emscripten')
      if (fs.existsSync(upstream)) {
        const currentPath = env.PATH || env.Path || ''
        env.PATH = `${upstream}${path.delimiter}${emsdkPath}${path.delimiter}${currentPath}`
        env.Path = env.PATH
        env.EMSDK = emsdkPath
        return env
      }
    }
  }

  return env
}

function hasAllOpenccFiles(dir) {
  if (!dir || !fs.existsSync(dir)) return false
  return REQUIRED_OPENCC_FILES.every((file) => fs.existsSync(path.join(dir, file)))
}

function findFile(dir, fileName, maxDepth = 5) {
  if (maxDepth < 0) return null
  try {
    const entries = fs.readdirSync(dir, { withFileTypes: true })
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name)
      if (entry.isFile() && entry.name === fileName) {
        return fullPath
      }
      if (entry.isDirectory()) {
        const found = findFile(fullPath, fileName, maxDepth - 1)
        if (found) return found
      }
    }
  } catch {
    // Ignore unreadable dirs
  }
  return null
}

// Search dynamically for OpenCC dictionaries generated by any native build directory
function findOpenccDir() {
  if (process.env.HANVI_OPENCC_DATA_DIR && hasAllOpenccFiles(process.env.HANVI_OPENCC_DATA_DIR)) {
    return path.resolve(process.env.HANVI_OPENCC_DATA_DIR)
  }

  const ignoreDirs = new Set([
    '.git',
    'node_modules',
    'web',
    'cmake-build-wasm',
    '.idea',
    '3rdparty',
    'desktop',
    'cli',
    'core',
    'cmake',
  ])

  const matches = []

  function search(dir, depth = 0) {
    if (depth > 3) return
    try {
      const entries = fs.readdirSync(dir, { withFileTypes: true })
      for (const entry of entries) {
        if (!entry.isDirectory()) continue
        if (depth === 0 && ignoreDirs.has(entry.name)) continue

        const fullPath = path.join(dir, entry.name)

        if (hasAllOpenccFiles(fullPath)) {
          const stat = fs.statSync(fullPath)
          matches.push({ path: fullPath, mtime: stat.mtimeMs })
        } else {
          search(fullPath, depth + 1)
        }
      }
    } catch {
      // Ignore unreadable directories
    }
  }

  search(rootDir)

  if (matches.length > 0) {
    matches.sort((a, b) => b.mtime - a.mtime)
    return matches[0].path
  }

  return null
}

function run(cmd, args, env) {
  console.log(`[build-core] Running: ${cmd} ${args.join(' ')}`)
  const isWin = process.platform === 'win32'

  let executable = cmd
  if (isWin && !cmd.includes('/') && !cmd.includes('\\')) {
    for (const ext of ['', '.exe', '.cmd', '.bat']) {
      const check = spawnSync('where', [cmd + ext], { env, stdio: 'ignore' })
      if (check.status === 0) {
        executable = cmd + ext
        break
      }
    }
  }

  const result = spawnSync(executable, args, {
    cwd: rootDir,
    env,
    stdio: 'inherit',
    shell: false,
  })

  if (result.error) {
    const fallback = spawnSync(cmd, args, {
      cwd: rootDir,
      env,
      stdio: 'inherit',
      shell: true,
    })
    if (fallback.status !== 0) {
      console.error(`[build-core] Command failed with exit code ${fallback.status}: ${cmd}`)
      process.exit(fallback.status ?? 1)
    }
    return
  }

  if (result.status !== 0) {
    console.error(`[build-core] Command failed with exit code ${result.status}: ${cmd}`)
    process.exit(result.status ?? 1)
  }
}

// Build OpenCC binary dictionaries (.ocd2) natively if no existing build folder has them
function buildOpenccDictionaries(env) {
  const nativeToolsDir = path.resolve(rootDir, 'cmake-build-native-tools')
  const openccOutDir = path.join(nativeToolsDir, 'opencc')

  if (hasAllOpenccFiles(openccOutDir)) {
    return openccOutDir
  }

  console.log('[build-core] No OpenCC dictionaries found. Building them natively with CMake...')
  fs.mkdirSync(nativeToolsDir, { recursive: true })

  const isWin = process.platform === 'win32'
  const checkCmd = isWin ? 'where' : 'which'
  const hasNinja = spawnSync(checkCmd, ['ninja'], { env, stdio: 'ignore' }).status === 0

  const configureArgs = [
    '-S',
    rootDir,
    '-B',
    nativeToolsDir,
    '-DHANVI_BUILD_DESKTOP=OFF',
    '-DHANVI_BUILD_CLI=OFF',
    '-DHANVI_BUILD_OPENCC_DICTIONARIES=ON',
    '-DCMAKE_BUILD_TYPE=Release',
  ]
  if (hasNinja) {
    configureArgs.push('-G', 'Ninja')
  }

  const cacheFile = path.join(nativeToolsDir, 'CMakeCache.txt')
  if (!fs.existsSync(cacheFile)) {
    console.log('[build-core] Configuring native OpenCC tools build...')
    run('cmake', configureArgs, env)
  }

  console.log('[build-core] Building native OpenCC Dictionaries target...')
  run('cmake', ['--build', nativeToolsDir, '--target', 'Dictionaries', '--config', 'Release'], env)

  // Find generated .ocd2 files and t2s.json
  const tsPhrasesPath = findFile(nativeToolsDir, 'TSPhrases.ocd2')
  const t2sPath = findFile(nativeToolsDir, 't2s.json')

  if (!tsPhrasesPath) {
    console.error('[build-core] Error: Failed to find generated TSPhrases.ocd2 in native tools build directory.')
    process.exit(1)
  }
  if (!t2sPath) {
    console.error('[build-core] Error: Failed to find t2s.json in native tools build directory.')
    process.exit(1)
  }

  const generatedOcd2Dir = path.dirname(tsPhrasesPath)
  fs.mkdirSync(openccOutDir, { recursive: true })

  fs.copyFileSync(t2sPath, path.join(openccOutDir, 't2s.json'))
  for (const file of [
    'TSPhrases.ocd2',
    'TSCharacters.ocd2',
    'TSCharactersExt.ocd2',
    'CJK_Compatibility_Ideographs.ocd2',
  ]) {
    const src = path.join(generatedOcd2Dir, file)
    if (!fs.existsSync(src)) {
      console.error(`[build-core] Error: Expected dictionary file not found: ${src}`)
      process.exit(1)
    }
    fs.copyFileSync(src, path.join(openccOutDir, file))
  }

  console.log(`[build-core] Successfully prepared OpenCC dictionaries in: ${openccOutDir}`)
  return openccOutDir
}

// Compress dict.db into dict.db.gz to satisfy Cloudflare Pages' 25MB asset limit
function compressDictionary() {
  const publicDataDir = path.resolve(rootDir, 'web/public/data')
  const uncompressedDb = path.join(publicDataDir, 'dict.db')
  const compressedDb = path.join(publicDataDir, 'dict.db.gz')

  if (fs.existsSync(uncompressedDb)) {
    console.log('[build-core] Compressing dict.db with gzip for Cloudflare Pages...')
    const data = fs.readFileSync(uncompressedDb)
    const gz = zlib.gzipSync(data, { level: 9 })
    fs.writeFileSync(compressedDb, gz)

    const rawMB = (data.length / (1024 * 1024)).toFixed(2)
    const gzMB = (gz.length / (1024 * 1024)).toFixed(2)
    console.log(`[build-core] Compressed dict.db: ${rawMB} MB -> ${gzMB} MB (saved to dict.db.gz)`)

    // Remove uncompressed file from public/data so it is not bundled into dist/
    fs.unlinkSync(uncompressedDb)
    console.log('[build-core] Removed uncompressed dict.db to stay under Cloudflare Pages 25MB limit.')
  }

  // Also clean up dist/data/dict.db if a previous build left it behind
  const distDb = path.resolve(rootDir, 'web/dist/data/dict.db')
  if (fs.existsSync(distDb)) {
    fs.unlinkSync(distDb)
  }
}

function main() {
  const env = setupEnv()

  const isWin = process.platform === 'win32'
  const checkCmd = isWin ? 'where' : 'which'
  const hasEmcmake = spawnSync(checkCmd, ['emcmake'], { env, stdio: 'ignore' }).status === 0

  if (!hasEmcmake) {
    console.error(
      '[build-core] Error: emcmake not found. Please activate Emscripten (e.g. source emsdk_env.sh) or install emsdk.',
    )
    process.exit(1)
  }

  const hasCmake = spawnSync(checkCmd, ['cmake'], { env, stdio: 'ignore' }).status === 0
  if (!hasCmake) {
    console.error('[build-core] Error: cmake not found in PATH.')
    process.exit(1)
  }

  let openccDir = process.env.FORCE_BUILD_OPENCC === '1' ? null : findOpenccDir()
  if (!openccDir) {
    openccDir = buildOpenccDictionaries(env)
  }

  console.log(`[build-core] Using OpenCC data directory at: ${openccDir}`)

  const cacheFile = path.join(wasmBuildDir, 'CMakeCache.txt')
  let needsConfigure = !fs.existsSync(cacheFile)

  if (!needsConfigure) {
    const cacheContent = fs.readFileSync(cacheFile, 'utf8')
    const match = cacheContent.match(/HANVI_OPENCC_DATA_DIR:PATH=(.*)/)
    if (!match || !match[1] || !fs.existsSync(match[1].trim())) {
      console.log('[build-core] Reconfiguring WebAssembly build because cached OpenCC directory is invalid or missing.')
      needsConfigure = true
    }
  }

  if (needsConfigure) {
    console.log('[build-core] Configuring WebAssembly build with emcmake...')
    const cmakeArgs = [
      'cmake',
      '-S',
      rootDir,
      '-B',
      wasmBuildDir,
      '-DCMAKE_BUILD_TYPE=Release',
      `-DHANVI_OPENCC_DATA_DIR=${openccDir.replace(/\\/g, '/')}`,
    ]

    const hasNinja = spawnSync(checkCmd, ['ninja'], { env, stdio: 'ignore' }).status === 0
    if (hasNinja) {
      cmakeArgs.push('-G', 'Ninja')
    }

    run('emcmake', cmakeArgs, env)
  }

  console.log('[build-core] Compiling HanviWasm target...')
  run('cmake', ['--build', wasmBuildDir, '--target', 'HanviWasm'], env)

  // Compress dictionary
  compressDictionary()

  console.log('[build-core] Core WebAssembly build complete.')
}

main()
